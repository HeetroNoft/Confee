package fr.heetstudio.confee.ui;

import fr.heetstudio.confee.ConfeeLog;
import fr.heetstudio.confee.platform.Services;
import net.minecraft.client.Minecraft;
import net.minecraft.core.Registry;
import net.minecraft.core.RegistryAccess;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.resources.ResourceKey;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.server.packs.PackType;
import net.minecraft.server.packs.VanillaPackResources;
import net.minecraft.server.packs.repository.ServerPacksSource;
import net.minecraft.tags.TagManager;
import org.jetbrains.annotations.Nullable;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.HashSet;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.Set;
import java.util.TreeSet;
import java.util.stream.Stream;

/**
 * IDs and tags of any registry, mods' entries included (spec 10.8):
 * <ul>
 *     <li>built-in registries (items, blocks, entity types... and those added by mods): the game registry;</li>
 *     <li>world registries (biomes, structures, dimensions...): the loaded world when there is one (single player
 *     server first, else what the server sent), otherwise the data files of the game and of every mod;</li>
 *     <li>tags: the loaded world, otherwise the tag files of the game and of every mod.</li>
 * </ul>
 * Results are cached per world. Client only.
 * <p>Internal: may change without notice.</p>
 */
public final class RegistryEntries {

    /** Vanilla dimensions are generated by the world preset, not data files. */
    private static final List<String> VANILLA_DIMENSIONS = List.of("minecraft:overworld", "minecraft:the_nether", "minecraft:the_end");

    private static final Map<String, List<String>> CACHE = new HashMap<>();
    private static final Set<String> WARNED = new HashSet<>();
    @Nullable
    private static Object cachedWorld;
    @Nullable
    private static VanillaPackResources vanillaData;

    private RegistryEntries() {
    }

    /** Sorted IDs of the registry (empty when unknown, logged once). */
    public static synchronized List<String> ids(String registry) {
        if (fr.heetstudio.confee.core.PseudoRegistries.isPseudo(registry)) {
            // installed mods: not a game registry
            return cached("ids|" + registry, () -> new HashSet<>(fr.heetstudio.confee.core.PseudoRegistries.ids(registry)));
        }
        return cached("ids|" + registry, () -> loadIds(registry));
    }

    /** Sorted tags of the registry, as {@code #namespace:path}. */
    public static synchronized List<String> tags(String registry) {
        if (fr.heetstudio.confee.core.PseudoRegistries.isPseudo(registry)) {
            return List.of(); // mods have no tags
        }
        return cached("tags|" + registry, () -> loadTags(registry));
    }

    /**
     * IDs in a tag, nested tags resolved: from the world when one is loaded, else from the tag files of the game and
     * of the mods.
     */
    public static synchronized Set<String> tagMembers(String registry, String tagId) {
        return new HashSet<>(cached("members|" + registry + "|" + tagId, () -> loadTagMembers(registry, tagId, new HashSet<>())));
    }

    @SuppressWarnings({"unchecked", "rawtypes"})
    private static Set<String> loadTagMembers(String registry, String tagId, Set<String> visiting) {
        Set<String> out = new HashSet<>();
        ResourceLocation tag = ResourceLocation.tryParse(tagId);
        if (tag == null || !visiting.add(tagId)) {
            return out;
        }
        RegistryAccess world = world();
        if (world != null) {
            Optional<? extends Registry<?>> found = world.registry((ResourceKey) key(registry));
            if (found.isPresent()) {
                Registry reg = found.get();
                Optional<?> set = reg.getTag(net.minecraft.tags.TagKey.create((ResourceKey) key(registry), tag));
                set.ifPresent(holders -> ((Iterable<net.minecraft.core.Holder<?>>) holders).forEach(holder ->
                        holder.unwrapKey().ifPresent(k -> out.add(((ResourceKey<?>) k).location().toString()))));
                if (!out.isEmpty()) {
                    return out;
                }
            }
        }
        // outside a world: the tag files ("values": IDs, "#tags", or {"id": ..., "required": false})
        String path = TagManager.getTagDir((ResourceKey) key(registry)) + "/" + tag.getPath() + ".json";
        List<String> jsons = new ArrayList<>();
        try {
            if (vanillaData == null) {
                vanillaData = new ServerPacksSource().getVanillaPack();
            }
            var resource = vanillaData.getResource(PackType.SERVER_DATA, new ResourceLocation(tag.getNamespace(), path));
            if (resource != null) {
                try (var in = resource.get()) {
                    jsons.add(new String(in.readAllBytes(), java.nio.charset.StandardCharsets.UTF_8));
                }
            }
        } catch (IOException | RuntimeException e) {
            ConfeeLog.warn("Cannot read the tag {}: {}", tagId, e.toString());
        }
        for (Path root : Services.PLATFORM.getModRootPaths()) {
            Path file = root.resolve("data").resolve(tag.getNamespace()).resolve(path);
            if (Files.isRegularFile(file)) {
                try {
                    jsons.add(Files.readString(file));
                } catch (IOException e) {
                    ConfeeLog.warn("Cannot read {}: {}", file, e.toString());
                }
            }
        }
        for (String json : jsons) {
            try {
                com.google.gson.JsonArray values = com.google.gson.JsonParser.parseString(json).getAsJsonObject().getAsJsonArray("values");
                if (values == null) {
                    continue;
                }
                for (com.google.gson.JsonElement value : values) {
                    String entry = value.isJsonObject() ? value.getAsJsonObject().get("id").getAsString() : value.getAsString();
                    if (entry.startsWith("#")) {
                        out.addAll(loadTagMembers(registry, entry.substring(1), visiting));
                    } else {
                        out.add(entry);
                    }
                }
            } catch (RuntimeException e) {
                ConfeeLog.warn("Cannot read the tag {}: {}", tagId, e.toString());
            }
        }
        return out;
    }

    private interface Loader {
        Set<String> load();
    }

    private static List<String> cached(String key, Loader loader) {
        Object world = world();
        if (world != cachedWorld) {
            CACHE.clear();
            cachedWorld = world;
        }
        return CACHE.computeIfAbsent(key, k -> {
            try {
                return List.copyOf(new TreeSet<>(loader.load()));
            } catch (RuntimeException | LinkageError e) {
                ConfeeLog.warn("Cannot list {}: {}", k, e.toString());
                return List.of();
            }
        });
    }

    /** Registries of the loaded world, or null on the title screen. */
    @Nullable
    private static RegistryAccess world() {
        Minecraft mc = Minecraft.getInstance();
        if (mc.getSingleplayerServer() != null) {
            return mc.getSingleplayerServer().registryAccess();
        }
        return mc.getConnection() != null ? mc.getConnection().registryAccess() : null;
    }

    private static ResourceKey<? extends Registry<?>> key(String registry) {
        return ResourceKey.createRegistryKey(new ResourceLocation(registry));
    }

    @SuppressWarnings({"unchecked", "rawtypes"})
    private static Optional<? extends Registry<?>> fromWorldOrGame(String registry) {
        RegistryAccess world = world();
        if (world != null) {
            Optional<? extends Registry<?>> found = world.registry((ResourceKey) key(registry));
            if (found.isPresent()) {
                return found;
            }
        }
        return Optional.ofNullable(BuiltInRegistries.REGISTRY.get(new ResourceLocation(registry)));
    }

    private static Set<String> loadIds(String registry) {
        Set<String> out = new HashSet<>();
        Optional<? extends Registry<?>> found = fromWorldOrGame(registry);
        if (found.isPresent()) {
            found.get().keySet().forEach(id -> out.add(id.toString()));
        } else {
            // world registry outside a world: the data files
            String dir = new ResourceLocation(registry).getPath();
            out.addAll(dataFiles(dir));
            if ("minecraft:dimension".equals(registry)) {
                out.addAll(VANILLA_DIMENSIONS);
            }
        }
        if (out.isEmpty() && WARNED.add(registry)) {
            ConfeeLog.warn("Unknown or empty registry '{}': no suggestions", registry);
        }
        out.remove("minecraft:air");
        return out;
    }

    @SuppressWarnings({"unchecked", "rawtypes"})
    private static Set<String> loadTags(String registry) {
        Set<String> out = new HashSet<>();
        Optional<? extends Registry<?>> found = fromWorldOrGame(registry);
        if (world() != null && found.isPresent()) {
            ((Registry) found.get()).getTagNames().forEach(tag -> out.add("#" + ((net.minecraft.tags.TagKey<?>) tag).location()));
        }
        if (out.isEmpty()) {
            // outside a world (tags are only bound in a world): the tag files
            for (String id : dataFiles(TagManager.getTagDir((ResourceKey) key(registry)))) {
                out.add("#" + id);
            }
        }
        return out;
    }

    /** IDs of {@code data/<namespace>/<dir>/**.json} in the game and in every mod. */
    private static Set<String> dataFiles(String dir) {
        Set<String> out = new HashSet<>();
        try {
            if (vanillaData == null) {
                vanillaData = new ServerPacksSource().getVanillaPack();
            }
            for (String namespace : vanillaData.getNamespaces(PackType.SERVER_DATA)) {
                vanillaData.listResources(PackType.SERVER_DATA, namespace, dir, (id, stream) -> addJson(out, id, dir));
            }
        } catch (RuntimeException e) {
            ConfeeLog.warn("Cannot read the game data files: {}", e.toString());
        }
        for (Path root : Services.PLATFORM.getModRootPaths()) {
            Path data = root.resolve("data");
            if (!Files.isDirectory(data)) {
                continue;
            }
            try (Stream<Path> namespaces = Files.list(data)) {
                for (Path ns : namespaces.toList()) {
                    Path folder = ns.resolve(dir);
                    if (!Files.isDirectory(folder)) {
                        continue;
                    }
                    String namespace = ns.getFileName().toString().replace("/", "");
                    try (Stream<Path> files = Files.walk(folder)) {
                        files.filter(p -> p.toString().endsWith(".json")).forEach(p -> {
                            String rel = folder.relativize(p).toString().replace('\\', '/');
                            String id = namespace + ":" + rel.substring(0, rel.length() - ".json".length());
                            if (ResourceLocation.isValidResourceLocation(id)) {
                                out.add(id);
                            }
                        });
                    }
                }
            } catch (IOException | RuntimeException e) {
                ConfeeLog.warn("Cannot list data files of {}: {}", root, e.toString());
            }
        }
        return out;
    }

    /** {@code namespace:<dir>/<name>.json} → {@code namespace:<name>}. */
    private static void addJson(Set<String> out, ResourceLocation file, String dir) {
        String path = file.getPath();
        if (path.endsWith(".json") && path.startsWith(dir + "/")) {
            out.add(file.getNamespace() + ":" + path.substring(dir.length() + 1, path.length() - ".json".length()));
        }
    }
}
